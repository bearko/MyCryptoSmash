/** 名前がまだないときの呼び方 */
export const DEFAULT_NAME = 'お客さん';
/** プレイヤー名のいちばん長い文字数 */
export const NAME_MAX = 10;
/** 入力された名前をととのえる（前後の空白を取り、10 文字まで。空なら「お客さん」） */
export function cleanName(raw: string): string {
  const s = Array.from((raw ?? '').replace(/[\s　]+/g, ' ').trim()).slice(0, NAME_MAX).join('').trim();
  return s || DEFAULT_NAME;
}

export interface LineCtx { name?: string; left?: number; rest?: string; tries?: number }
/** セリフに名前などを差しこむ */
export function fillLine(text: string, ctx: LineCtx = {}): string {
  return text
    .replace(/\{name\}/g, ctx.name || DEFAULT_NAME)
    .replace(/\{left\}/g, String(ctx.left ?? 0))
    .replace(/\{rest\}/g, ctx.rest ?? '0')
    .replace(/\{tries\}/g, String(ctx.tries ?? 0));
}
/** その姿・場面のセリフ（名前などを差しこんだもの） */
export function clownLines(scene: ClownScene, tier: number): string[] {
  return CLOWN_TABLE[Math.max(0, Math.min(CLOWN_TABLE.length - 1, tier))][scene];
}
/** その姿・場面のセリフを 1 つ選ぶ（前と同じものはなるべく避ける） */
let lastLine = '';
export function clownLine(scene: ClownScene, tier: number, ctx: LineCtx = {}, rng: () => number = Math.random): string {
  const list = clownLines(scene, tier);
  let pick = list[Math.floor(rng() * list.length) % list.length];
  if (pick === lastLine && list.length > 1) pick = list[(list.indexOf(pick) + 1) % list.length];
  lastLine = pick;
  return fillLine(pick, ctx);
}
/** プレイの前の場面：最後の 1 プレイ・もう納められる・ふつう */
export function preScene(left: number, canPay: boolean): ClownScene {
  if (canPay) return 'ready';
  return left <= 1 ? 'lastPlay' : 'prePlay';
}

